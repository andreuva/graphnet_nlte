print("Generating Plot 2: Height-Color-Coded Scatter...")
fig_scatter, axes_scatter = plt.subplots(3, 2, figsize=(10, 13), dpi=150, sharex=True, sharey=True, gridspec_kw={'hspace': 0.03, 'wspace': 0.03})
axes_scatter = axes_scatter.flatten()
