for i in range(nlev):
    ax = axes_scatter[i]
    # randomly sample 100k points for plotting to avoid overcrowding
    # if len(targets_denorm_flat) > 500000:
    #     sample_indices = np.random.choice(len(targets_denorm_flat), size=500000, replace=False)
