# Replace with the actual paths generated by your inference script
predictions_path = f'/dat/andreuva/gpu/graphnet/graphnet_nlte/checkpoints/multistride_cpudtst_4x4_s4_m8_b8_r6_d025_press/predictions_patch_stride_{stride}_{dataset_size}.npy'
targets_path = f'/dat/andreuva/gpu/graphnet/graphnet_nlte/checkpoints/multistride_cpudtst_4x4_s4_m8_b8_r6_d025_press/targets_patch_stride_{stride}_{dataset_size}.npy'
savedir = f'/dat/andreuva/gpu/graphnet/graphnet_nlte/checkpoints/multistride_cpudtst_4x4_s4_m8_b8_r6_d025_press/' # Directory where plots will be saved

