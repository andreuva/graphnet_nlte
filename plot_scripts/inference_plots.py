# ==========================================
# PLOT 3: HEIGHT-COLOR-CODED ANALYSIS
# ==========================================
print("Generating Plot 3: Height-Color-Coded Analysis...")
fig_comp, axes_comp = plt.subplots(nlev, 2, figsize=(10, 13), dpi=150, sharex='col', 
                                   gridspec_kw={'hspace': 0.15, 'wspace': 0.1})

height_groups = {
    f'Bottom (z < 2) Mm': (z_indices_flat < 25),
    f'Middle (2 < z < 4) Mm': (z_indices_flat >= 25) & (z_indices_flat < 37),
    f'Top (z >= 4) Mm': (z_indices_flat >= 37)
}
colors_list = ['blue', 'green', 'red']

for i in range(nlev):
    # --- Column 1: Residuals ---
    ax1 = axes_comp[i, 0]
    all_residuals = residuals_denorm[:, i] * 100
    lower, upper = -50, 50 
    
    for color, (label, mask) in zip(colors_list, height_groups.items()):
        data = all_residuals[mask]
        ax1.hist(data, bins=100, range=(lower, upper), density=True, alpha=0.5, label=label, color=color)

    ax1.axvline(0, color='k', linestyle='--')
    if i == 0: ax1.set_title(f'Residuals (Original)', fontsize=16)
    if i == nlev-1: ax1.set_xlabel('Relative Error (%)', fontsize=16)
    
    ax1.set_ylabel(r'$Ca_{II}$'+f' (i={i})', fontsize=16)
    if i == nlev - 1:
        ax1.set_ylabel(r'$Ca_{III}$', fontsize=16)
    # ax1.grid(True, linestyle='--', alpha=0.5)

    # --- Column 2: Distributions ---
    ax2 = axes_comp[i, 1]
    valid_mask = (targets_denorm_flat[:, i] > 0)
    
    if np.any(valid_mask):
        bins = np.logspace(np.log10(targets_denorm_flat[valid_mask, i].min()), 
                           np.log10(targets_denorm_flat[:, i].max()), 75)
        
        for color, (label, mask) in zip(colors_list, height_groups.items()):
            ax2.hist(targets_denorm_flat[valid_mask & mask, i], bins=bins, 
                     alpha=0.6, label=f'Actual ({label})', 
                     histtype='step', linewidth=2, color=color)
            ax2.hist(predictions_denorm_flat[valid_mask & mask, i], bins=bins,  label=f'Predicted ({label})',
                     alpha=0.6, histtype='stepfilled', hatch='//', edgecolor=color, facecolor='none')

    if i == 0: ax2.set_title(f'Population Distribution', fontsize=16)
    if i == nlev-1: ax2.set_xlabel('Population', fontsize=16)
    
    ax2.set_xscale('log')
    # ax2.grid(True, linestyle='--', alpha=0.5)
    ax2.ticklabel_format(axis='y', style='sci', scilimits=(0,0), useMathText=True)
    ax2.locator_params(axis='y', nbins=5)
    
    # Legend on first row only
    if i == 0:
        ax1.legend(framealpha=0.5, facecolor='white', loc='upper right', fontsize=12)
        # ax2.legend(framealpha=0.5, facecolor='white', loc='upper right', fontsize=8)

