# ==========================================
# 2. LOAD DATA AND RECONSTRUCT GRID
# ==========================================
print(f"Loading saved populations, s={stride}, {dataset_size}...")
predictions_denorm = np.load(predictions_path)
targets_denorm = np.load(targets_path)

new_nz, ny_size, nx_size, nlev = targets_denorm.shape
print(f"Loaded spatial cubes of shape: {targets_denorm.shape}")

print("Reconstructing geometry grid from checkpoint config...")
checkpoint = torch.load(checkpoint_path, map_location='cpu', weights_only=False)
config = checkpoint['config']
nz = config['data']['nz_orig']
nz_linear = config['dataset']['nz_linear']
nz_log = config['dataset']['nz_log']
logspace_fraction = config['dataset']['logspace_fraction']

z = np.arange(nz)
new_z_log = np.concatenate([
    np.linspace(0, nz * logspace_fraction, nz_linear, endpoint=False),
    np.logspace(np.log10(nz * logspace_fraction), np.log10(nz - 1), nz_log)
])
new_z = np.clip(new_z_log, 0, nz - 1)
geometry_grid = np.load(config["data"]["grid_file"])["z"]
zz_grid = np.interp(new_z, z, geometry_grid)

# ==========================================
# 3. DATA FLATTENING & FILTERING
# ==========================================
print("Flattening data and filtering out padded background...")
# Reshape to (pixels, nlev)
predictions_denorm_flat_all = predictions_denorm.reshape(-1, nlev)
targets_denorm_flat_all = targets_denorm.reshape(-1, nlev)

# Create corresponding z-indices for each pixel
z_indices = np.arange(new_nz).reshape(new_nz, 1, 1).repeat(ny_size, axis=1).repeat(nx_size, axis=2)
z_indices_flat_all = z_indices.flatten()

# Filter out zero-padding (pixels where target is 0)
valid_pixels = targets_denorm_flat_all[:, 0] > 0

predictions_denorm_flat = predictions_denorm_flat_all[valid_pixels]
targets_denorm_flat = targets_denorm_flat_all[valid_pixels]
z_indices_flat = z_indices_flat_all[valid_pixels]
z_grid_flat = zz_grid[z_indices_flat]

# Calculate errors
residuals_denorm = (predictions_denorm_flat - targets_denorm_flat) / (targets_denorm_flat + 1e-12)
mae_denorm = np.mean(np.abs(residuals_denorm), axis=0)
rmse_denorm = np.sqrt(np.mean(residuals_denorm**2, axis=0))

print("Data preparation complete. Generating plots...")

# ==========================================
# PLOT 1: SPATIAL ERROR MAPS
# ==========================================
print("Generating Plot 1: Spatial Inference Maps...")
z_slices = [6, 20, 35, 45]   
cols = len(z_slices)
rows = nlev + 1          

# Ensure the list is long enough for your rows, or default to None if out of bounds
def get_highlight_col(row_idx):
    if row_idx < len(highlight_map):
        return highlight_map[row_idx]
    return None

fig, axes = plt.subplots(rows, cols, figsize=(10, 18), dpi=150,
                         constrained_layout=True, gridspec_kw={'wspace': 0, 'hspace': 0})

for r in range(rows): 
    for col_idx, z_idx in enumerate(z_slices): 
        ax = axes[r, col_idx]
        
        if r == 0:
            targ_panel = targets_denorm[z_idx, :, :, 0]
            # Handle zeroes for log space in empty padding regions
            targ_panel_safe = np.where(targ_panel > 0, targ_panel, np.nan)
            im_targ = ax.imshow(np.log10(targ_panel_safe), cmap='magma', origin='lower')
            
            if col_idx == 0:
                ax.set_ylabel(r"$n_{Ca_{II}}\ (i=0)$", fontsize=18, fontweight='bold')
            
            cbar = fig.colorbar(im_targ, ax=ax, location='top', fraction=0.05, pad=0.02)
            cbar.set_label(r'$log_{10}(\ n ($' + f'z={zz_grid[z_idx]:1.1f} Mm))', fontsize=16)
            cbar.ax.xaxis.set_ticks_position('top')
            cbar.ax.xaxis.set_label_position('top')
            cbar.ax.tick_params(labelsize=12)
            cbar.locator = ticker.MaxNLocator(nbins=5)
            cbar.update_ticks()

        else:
            lvl = r - 1
            pred_panel = predictions_denorm[z_idx, :, :, lvl]
            targ_panel = targets_denorm[z_idx, :, :, lvl]
            
            with np.errstate(divide='ignore', invalid='ignore'):
                diff = np.log10(pred_panel) - np.log10(targ_panel)
                diff_vol_at_z = np.log10(predictions_denorm[z_idx, :, :, :]) - np.log10(targets_denorm[z_idx, :, :, :])
            
            diff_vol_at_z = diff_vol_at_z[~np.isnan(diff_vol_at_z) & ~np.isinf(diff_vol_at_z)]
            vmax = np.percentile(np.abs(diff_vol_at_z), 92) if len(diff_vol_at_z) > 0 else 1.0
            vmin = -vmax
            
            im_err = ax.imshow(diff, cmap='RdBu_r', vmin=vmin, vmax=vmax, origin='lower')
            
            if r == rows - 1 and col_idx == 0:
                ax.set_ylabel(r"$\epsilon_{Ca_{III}}$", fontsize=18)
            elif col_idx == 0:
                ax.set_ylabel(r"$\epsilon_{Ca_{II}}$" + f" (i={lvl})", fontsize=18)
                
            if r == rows - 1:
                cbar = fig.colorbar(im_err, ax=ax, orientation='horizontal', fraction=0.05, pad=0.05)
                cbar.set_label('Error (dex)', fontsize=16)
                cbar.ax.tick_params(labelsize=12)
                cbar.locator = ticker.MaxNLocator(nbins=4)
                cbar.update_ticks()

        current_highlight = get_highlight_col(r)

        # --- DYNAMIC HIGHLIGHT LOGIC ---
        if current_highlight is not None and col_idx == current_highlight:
            # Add a thick green border
            for spine in ax.spines.values():
                spine.set_edgecolor(highlight_color)
                spine.set_linewidth(4)
                spine.set_visible(True)
            
            # Optional: Add an overlay rectangle for extra emphasis
            # rect = patches.Rectangle((0, 0), 1, 1, linewidth=0, edgecolor='none',
            #                          facecolor=highlight_color, alpha=0.1, 
            #                          transform=ax.transAxes, zorder=5)
            # ax.add_patch(rect)
        # else:
            # Ensure non-highlighted cells have no visible spines to maintain the grid look
            # for spine in ax.spines.values():
                # spine.set_visible(False)

        ax.set_xticks([])
        ax.set_yticks([])

# plt.tight_layout()
plt.savefig(os.path.join(savedir, f'1_inference_maps_stride_{stride}_{dataset_size}.pdf'), bbox_inches='tight')
